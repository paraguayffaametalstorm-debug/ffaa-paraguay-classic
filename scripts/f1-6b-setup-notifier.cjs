const CONTROLLER_PATH = 'src/controllers/tournaments.controller.js';

function applyControllerHook(absPath, opts) {
  const name = opts.name;
  const find = opts.find;
  const replace = opts.replace;

  const current = fs.readFileSync(absPath, 'utf8');

  if (current.includes(replace.trim())) {
    skip('  hook ' + name + ': ya aplicado');
    return;
  }
  if (!current.includes(find.trim())) {
    warn('  hook ' + name + ": bloque 'find' no encontrado");
    return;
  }

  const updated = current.replace(find, replace);
  if (!DRY_RUN) {
    const bk = backup(absPath);
    if (bk) ok('  backup: ' + path.relative(ROOT, bk));
    fs.writeFileSync(absPath, updated, 'utf8');
  }
  ok('  hook ' + name + ': aplicado');
}

